const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const { canStoreExperience } = useConsent();

  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window !== 'undefined' && canStoreExperience) {
      const saved = localStorage.getItem('app_language');
      if (saved === 'en' || saved === 'pt') return saved;
    }
    return 'pt';
  });

  useEffect(() => {
    if (typeof window !== 'undefined') {
      document.documentElement.lang = language === 'pt' ? 'pt-BR' : 'en';
      if (canStoreExperience) {
        localStorage.setItem('app_language', language);
      }
    }
  }, [language, canStoreExperience]);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    if (typeof window !== 'undefined') {
      document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
      if (canStoreExperience) {
        localStorage.setItem('app_language', lang);
      }
    }
  };

  const toggleLanguage = () => {
    setLanguage(language === 'pt' ? 'en' : 'pt');
  };

  const t = (key: string, defaultFallback?: string) => {
    return translations[language]?.[key] || defaultFallback || translations['pt']?.[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ 
      language, 
      currentLang: language, 
      setLanguage, 
      toggleLanguage, 
      t, 
      dictionary: translations[language] || translations.pt 
    }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
